"""Write the emulation files for an import plan: Renode board and script, External Control bindings, the mechatronic
project (firmware + motion plant + instruments) and the import report."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from .analysis import Device, Plan

FEED_BASE = 0x5F000000
FEED_SCRIPT = """
if request.IsInit:
    from System import BitConverter, Convert, UInt32
    from Antmicro.Renode.Core import EmulationManager
    TARGETS = {TARGETS}
    values = {{}}
    resolved = {{}}
elif request.IsWrite:
    values[request.Offset] = request.Value
    if request.Offset in TARGETS:
        path, name, scale = TARGETS[request.Offset]
        if (path, name) not in resolved:
            found, machine = EmulationManager.Instance.CurrentEmulation.TryGetMachineForPeripheral(self)
            target = machine[path]
            resolved[(path, name)] = (target, target.GetType().GetProperty(name))
        target, prop = resolved[(path, name)]
        number = BitConverter.ToSingle(BitConverter.GetBytes(UInt32(request.Value & 0xFFFFFFFF)), 0) * scale
        prop.SetValue(target, Convert.ChangeType(float(number), prop.PropertyType), None)
elif request.IsRead:
    request.Value = values.get(request.Offset, 0)
"""

# plant output per sensor quantity component (the PendulumMount names)
QUANTITY_SIGNALS = {
    "acceleration": ["acc_x", "acc_y", "acc_z"],
    "angular_rate": ["gyro_x", "gyro_y", "gyro_z"],
    "pressure": ["pressure"],
    "temperature": ["temperature"],
}
SI_UNITS = {"acceleration": "m/s^2", "angular_rate": "rad/s", "pressure": "Pa", "temperature": "degC"}


def _mux(device: Device) -> str:
    return f"{device.bus}Mux"


def device_path(device: Device) -> str:
    if device.bus_kind == "spi":
        return f"sysbus.{device.bus}.{_mux(device)}.{device.instance}"
    return f"sysbus.{device.bus}.{device.instance}"


def board_repl(plan: Plan, title: str) -> str:
    lines = [f"// {title}: generated by `embeddyn mechatronics import` from the schematic netlist and the CubeMX project.",
             f"// MCU {plan.mcu_ref} {plan.mcu_part}. Edit the import inputs and re-run rather than this file.",
             f'using "{plan.platform}"', ""]
    if plan.hse_hz:
        lines += ["rcc:", f"    hseFrequency: {plan.hse_hz}", ""]
    spi_devices: dict[str, list[Device]] = {}
    for device in plan.devices:
        if device.bus_kind == "spi":
            spi_devices.setdefault(device.bus, []).append(device)
    for bus, devices in sorted(spi_devices.items()):
        lines += [f"// {bus.upper()}: chip selects (active low) select the devices; several selected at once share the",
                  "// bus as on the board (MISO is their wired-AND)",
                  f"{bus}Mux: SPI.SPIMultiplexer @ {bus}", "    multipleSelection: true", "    init:"]
        for index, device in enumerate(devices):
            lines.append(f"        SetActiveLow {index}")
        lines.append("")
        for index, device in enumerate(devices):
            if device.cs:
                lines += [f"{device.cs.gpio}:", f"    {device.cs.number} -> {bus}Mux@{index}", ""]
            lines.append(f"// {device.ref} {device.title} ({device.name}), CS {device.cs.name if device.cs else '?'}")
            lines.append(f"{device.instance}: {device.model} @ {bus}Mux {index}")
            for prop, pin in device.outputs.items():
                lines.append(f"    {prop} -> {pin.gpio}@{pin.number}")
            lines.append("")
    for device in plan.devices:
        if device.bus_kind == "i2c":
            lines += [f"// {device.ref} {device.title} ({device.name})",
                      f"{device.instance}: {device.model} @ {device.bus} 0x{device.i2c_address or 0:X}"]
            for prop, pin in device.outputs.items():
                lines.append(f"    {prop} -> {pin.gpio}@{pin.number}")
            lines.append("")
    for led in plan.leds:
        lines += [f"// {led.ref} {led.color} LED on {led.pin.name}" + (" (active low)" if led.active_low else "")
                  + (f", {led.series_ohm:g} ohm" if led.series_ohm else ""),
                  f"{led.instance}: Miscellaneous.LED @ {led.pin.gpio} {led.pin.number}"]
        if led.active_low:
            lines.append("    invert: true")
        lines += ["", f"{led.pin.gpio}:", f"    {led.pin.number} -> {led.instance}@0", ""]
    if plan.usb:
        lines += ["// USB device on PA11/PA12: a USB host that turns its CDC (serial) interface into a UART",
                  "usbSerial: USB.USBSerialHost @ sysbus", ""]
    feeds = feed_targets(plan)
    if feeds:
        targets = "{" + ", ".join(f"0x{offset:02X}: (\"{path}\", \"{prop}\", {scale!r})"
                                  for offset, (path, prop, scale, _) in sorted(feeds.items())) + "}"
        lines += ["// Sensor feed bridge (not hardware): embeddyn writes float32 SI values into the slots; the script sets",
                  "// the sensor model properties, converted to their units.",
                  f"sensorFeed: Python.PythonPeripheral @ sysbus 0x{FEED_BASE:08X}",
                  f"    size: 0x{max(0x40, 4 * (len(feeds) + 1)):X}", "    initable: true", "    script: '''" +
                  FEED_SCRIPT.replace("{TARGETS}", targets).replace("{{", "{").replace("}}", "}") + "'''", ""]
    return "\n".join(lines).rstrip() + "\n"


def feed_targets(plan: Plan) -> dict[int, tuple[str, str, float, str]]:
    """Feed slot offset -> (model path, property, SI-to-model scale, plant output)."""
    feeds: dict[int, tuple[str, str, float, str]] = {}
    offset = 0
    for device in plan.devices:
        for quantity, spec in device.quantities.items():
            outputs = QUANTITY_SIGNALS.get(quantity)
            if not outputs:
                continue
            for prop, output in zip(spec["properties"], outputs):
                feeds[offset] = (device_path(device), prop, float(spec.get("from_si", 1.0)), output)
                offset += 4
    return feeds


def board_resc(plan: Plan, firmware: str | None, renode_root: str | None = None) -> str:
    lines = ["# Renode script for the imported board (firmware domain). embeddyn runs Renode with",
             "#   -e '$bin=@<firmware>; include @<this file>; emulation CreateExternalControlServer ...'",
             "# and advances virtual time itself: do not `start` here.", ""]
    if renode_root:
        lines += ["# the Renode tree with the platform files (`using \"platforms/...\"` in board.repl)",
                  f"$renode_root?=@{renode_root}", "path add $renode_root"]
    lines += ['mach create "board"', "machine LoadPlatformDescription $ORIGIN/board.repl"]
    if firmware:
        lines.append(f"$bin?=$ORIGIN/{firmware}")
    lines += ["sysbus LoadELF $bin"]
    if plan.usb:
        lines.append(f"usbSerial Attach sysbus.{plan.usb_peripheral}")
    lines += ["logLevel 3 sysbus", '$quantum?="0.00001"', "emulation SetGlobalQuantum $quantum", ""]
    return "\n".join(lines)


def bindings(plan: Plan) -> dict[str, Any]:
    items: list[dict[str, Any]] = []
    for offset, (path, prop, scale, output) in sorted(feed_targets(plan).items()):
        device = path.rsplit(".", 1)[-1]
        items.append({"signal": f"motion.{output}",
                      "endpoint": {"object": "sysbus", "property": "sysbus", "address": FEED_BASE + offset,
                                   "float32": True, "direction": "input"},
                      "comment": f"{device}.{prop} (x{scale:g})"})
    for led in plan.leds:
        items.append({"signal": f"board.{led.instance}",
                      "endpoint": {"object": f"sysbus.{led.pin.gpio}", "property": "gpio_duty", "pin": led.pin.number,
                                   "direction": "output"},
                      "comment": f"{led.ref} {led.color} LED pin {led.pin.name} duty"
                                 + (" (active low: brightness = 1 - duty)" if led.active_low else "")})
    return {"adapter": "renode", "machine": "board", "bindings": items}


def project(plan: Plan, name: str, firmware: str | None, duration: float = 2.0) -> dict[str, Any]:
    signals: dict[str, Any] = {}
    channels_feed = sorted({output for _, (_, _, _, output) in feed_targets(plan).items()})
    for output in channels_feed:
        quantity = next(q for q, outs in QUANTITY_SIGNALS.items() if output in outs)
        signals[f"motion.{output}"] = {"domain": "mechanical", "unit": SI_UNITS[quantity],
                                       "initial": 9.80665 if output == "acc_z" else 101325.0 if output == "pressure"
                                       else 22.0 if output == "temperature" else 0.0}
    signals["motion.angle_deg"] = {"domain": "mechanical", "unit": "deg", "initial": 0.0}
    for led in plan.leds:
        signals[f"board.{led.instance}"] = {"domain": "firmware", "initial": 1.0 if led.active_low else 0.0}
        signals[f"{led.instance}.brightness"] = {"domain": "electrical", "initial": 0.0}
    renode: dict[str, Any] = {"backend": "renode", "launch": True, "script": "board.resc", "machine": "board",
                              "port": 21300, "bindings": "bindings.yaml", "variables": {"quantum": "0.00001"},
                              "log": "renode.log"}
    if firmware:
        renode["firmware"] = firmware
    nodes: list[dict[str, Any]] = []
    if plan.usb:
        renode["uarts"] = [{"name": "usb", "peripheral": "sysbus.usbSerial", "signal": "board.usb"}]
        signals["board.usb"] = {"domain": "firmware", "kind": "event"}
        nodes.append({"id": "usb", "kind": "instrument", "part": "serial_monitor", "label": "USB CDC (virtual COM port)",
                      "icon": "terminal", "settings": {"line_end": "CRLF"},
                      "ports": [{"name": "A", "direction": "in", "unit": ""}], "channels": {"A": "board.usb"}})
    motion_outputs = {output: f"motion.{output}" for output in channels_feed}
    motion_outputs["angle_deg"] = "motion.angle_deg"
    instances: dict[str, Any] = {
        "board": {"domain": "firmware", "options": renode},
        "motion": {"domain": "mechanical", "model": "embeddyn.mechatronics.motion:PendulumMount",
                   "options": {"backend": "python", "max_step": 1.0e-4,
                               "parameters": {"length": 0.5, "damping": 0.05, "angle": 30.0, "altitude": 120.0,
                                              "temperature": 22.0, "axes": "x,y,z"},
                               "outputs": motion_outputs}},
    }
    for led in plan.leds:
        instances[led.instance] = {"domain": "electrical", "model": "embeddyn.mechatronics.indicators:LedBrightness",
                                   "options": {"backend": "python", "max_step": 1.0e-3,
                                               "parameters": {"active_low": led.active_low, "tau": 0.02},
                                               "inputs": {"duty": f"board.{led.instance}"},
                                               "outputs": {"brightness": f"{led.instance}.brightness"}}}
    scope = [f"motion.{o}" for o in ("acc_x", "acc_z", "gyro_y", "angle_deg") if f"motion.{o}" in signals][:4]
    if scope:
        nodes.append({"id": "scope", "kind": "instrument", "part": "oscilloscope", "label": "board motion",
                      "icon": "scope", "settings": {"timebase": "all", "mode": "roll", "layout": "stack"},
                      "ports": [{"name": chr(65 + i), "direction": "in", "unit": ""} for i in range(len(scope))],
                      "channels": {chr(65 + i): s for i, s in enumerate(scope)}})
    for led in plan.leds:
        nodes.append({"id": led.instance, "kind": "instrument", "part": "led", "label": f"{led.ref} {led.color} ({led.pin.name})",
                      "icon": "led", "settings": {"threshold": 0.5, "color": {"red": "#ff3b30", "green": "#34c759",
                                                                               "blue": "#0a84ff"}.get(led.color, "#ffcc00"),
                                                  "dimmable": True},
                      "ports": [{"name": "A", "direction": "in", "unit": ""}], "channels": {"A": f"{led.instance}.brightness"}})
    metrics: dict[str, Any] = {}
    for led in plan.leds:
        metrics[f"{led.instance}_brightness"] = {"type": "stats", "signal": f"{led.instance}.brightness"}
    return {
        "name": name, "step_seconds": 0.001, "duration_seconds": duration,
        "metadata": {"description": f"{name}: imported board ({plan.mcu_part}) running its own firmware in Renode, "
                                    "on a pendulum mount that moves its IMU and barometer.",
                     "gui": {"nodes": nodes}},
        "instances": instances, "signals": signals, "metrics": metrics,
    }


def report(plan: Plan, title: str, extra: dict[str, Any]) -> str:
    lines = [f"# Import report: {title}", "", f"MCU: **{plan.mcu_ref} {plan.mcu_part}** -> `{plan.platform}`"
             + (f", HSE {plan.hse_hz / 1e6:g} MHz" if plan.hse_hz else ""), ""]
    if extra.get("firmware"):
        lines += ["## Firmware", ""]
        for item in extra["firmware"]:
            lines.append(f"- {item}")
        lines.append("")
    lines += ["## Emulated hardware", "", "| Ref | Part | Model | Bus | Select / address | Interrupts |", "|---|---|---|---|---|---|"]
    for d in plan.devices:
        select = d.cs.name if d.cs else (f"0x{d.i2c_address:02X}" if d.i2c_address is not None else "")
        interrupts = ", ".join(f"{k} -> {v.name}" for k, v in d.outputs.items())
        lines.append(f"| {d.ref} | {d.title} | `{d.model}` | {d.bus.upper()} | {select} | {interrupts} |")
    for led in plan.leds:
        lines.append(f"| {led.ref} | {led.color} LED | `Miscellaneous.LED` | GPIO | {led.pin.name}"
                     f"{' (active low)' if led.active_low else ''} | |")
    if plan.usb:
        lines.append("| USB | USB device (OTG FS) | `USB.USBSerialHost` attached | USB | PA11/PA12 | |")
    lines.append("")
    if plan.rails:
        lines += ["## Supply", ""]
        for rail in plan.rails:
            lines.append(f"- {rail.ref}: {rail.net} = {rail.volts:.3f} V" + (f" (nominal {rail.nominal} V)" if rail.nominal else "")
                         + f"; {rail.detail}")
        lines.append("")
    if plan.findings:
        lines += ["## Findings", ""]
        for finding in plan.findings:
            lines.append(f"- **{finding.level}**: {finding.message}")
        lines.append("")
    if plan.unmatched:
        lines += ["## Not emulated", "", "Parts the library does not know (add them to a parts YAML with `--parts`): "
                  + ", ".join(plan.unmatched), ""]
    lines += ["## Mechanics", "",
              "The board sits on a pendulum mount (`embeddyn.mechatronics.motion:PendulumMount`): its IMU sees the "
              "swing (specific force and angular rate in the board frame) and its barometer the height. Sensor axes "
              "are taken as aligned with the board; set `axes` for a rotated part, or replace the `motion` instance "
              "with a replay (CSV) or MuJoCo body.", ""]
    return "\n".join(lines)


def write_all(plan: Plan, out: Path, title: str, firmwares: list[Path], extra: dict[str, Any],
              renode_root: str | None = None) -> dict[str, Path]:
    """Write the board files once and a project per firmware (project.yaml is the first one)."""
    out.mkdir(parents=True, exist_ok=True)
    firmware_rels: list[str] = []
    for firmware in firmwares:
        target = out / "firmware" / firmware.name
        target.parent.mkdir(exist_ok=True)
        if firmware.resolve() != target.resolve():
            target.write_bytes(firmware.read_bytes())
        firmware_rels.append(f"firmware/{firmware.name}")
    primary = firmware_rels[0] if firmware_rels else None
    files = {
        "board.repl": board_repl(plan, title),
        "board.resc": board_resc(plan, primary, renode_root),
        "bindings.yaml": yaml.safe_dump(bindings(plan), sort_keys=False),
        "project.yaml": yaml.safe_dump(project(plan, title, primary), sort_keys=False),
        "report.md": report(plan, title, extra),
    }
    for rel in firmware_rels[1:]:
        stem = Path(rel).stem
        files[f"project-{stem}.yaml"] = yaml.safe_dump(project(plan, f"{title} ({stem})", rel), sort_keys=False)
    written = {}
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
        written[name] = out / name
    summary = {
        "mcu": {"ref": plan.mcu_ref, "part": plan.mcu_part, "platform": plan.platform, "hse_hz": plan.hse_hz},
        "devices": [{"ref": d.ref, "name": d.name, "model": d.model, "bus": d.bus, "cs": d.cs.name if d.cs else None,
                     "i2c_address": d.i2c_address, "outputs": {k: v.name for k, v in d.outputs.items()},
                     "path": device_path(d)} for d in plan.devices],
        "leds": [{"ref": l.ref, "color": l.color, "pin": l.pin.name, "active_low": l.active_low} for l in plan.leds],
        "rails": [{"ref": r.ref, "net": r.net, "volts": r.volts, "nominal": r.nominal} for r in plan.rails],
        "usb": plan.usb, "findings": [f.as_dict() for f in plan.findings], "unmatched": plan.unmatched,
        "firmware": firmware_rels, "projects": [n for n in files if n.startswith("project")],
    }
    (out / "import.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    written["import.json"] = out / "import.json"
    return written
