"""Export embeddyn python plants as FMI 3.0 co-simulation FMUs, and check FMUs with FMPy.

`export_plant("embeddyn.mechatronics.plants:RCServo", "dist/")` writes
``RCServo.fmu``. Inside, a PythonFMU3 slave wraps the plant class:

* plant inputs and outputs become FMU inputs and outputs. An input's start
  value is `input_start[name]`, else the value of a constructor parameter with
  the same name (RCServo `supply`), else 0. This matters because an FMU input
  always has a value, while an unmapped embeddyn input falls back to the
  plant's own default;
* numeric constructor parameters become tunable FMU parameters (strings and
  sequences are fixed at their export value);
* the ODE states are local variables, so ``canGetAndSetFMUState`` and
  ``canSerializeFMUState`` hold and importers can checkpoint and roll back;
* each ``doStep`` integrates with the same fixed-step RK4 sub-stepping
  (``max_step``) as embeddyn's python backend, so the FMU reproduces an
  embeddyn run.

The plant's module file is copied into the FMU, so it must use only the
standard library. All built-in plants do. The FMU needs a Python 3
interpreter on the importing machine (a PythonFMU3 property).

`check_fmu(path)` runs FMPy's model-description validation and a short
simulation, the first check before an FMU enters a project.
"""
from __future__ import annotations

import importlib
import inspect
import keyword
import shutil
import tempfile
import textwrap
from pathlib import Path
from typing import Any, Mapping

from .adapters.python_model import load_plant_class

_TEMPLATE = '''\
"""FMU slave generated by embeddyn.mechatronics.fmi_export for {reference}."""
import math

from pythonfmu3 import Fmi3Causality, Fmi3Slave, Fmi3Variability, Float64

from {module} import {cls} as _Plant

PARAMETERS = {parameters!r}
FIXED = {fixed!r}
INPUTS = {inputs!r}
INPUT_START = {input_start!r}
OUTPUTS = {outputs!r}
STATES = {states!r}
MAX_STEP = {max_step!r}


class {name}(Fmi3Slave):
    author = "embeddyn"
    description = {description!r}

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        for fmu_name, (plant_name, value) in PARAMETERS.items():
            setattr(self, fmu_name, float(value))
            self.register_variable(Float64(fmu_name, causality=Fmi3Causality.parameter,
                                           variability=Fmi3Variability.tunable, start=float(value)))
        for port in INPUTS:
            setattr(self, port, float(INPUT_START[port]))
            self.register_variable(Float64(port, causality=Fmi3Causality.input, start=float(INPUT_START[port])))
        for port in OUTPUTS:
            setattr(self, port, 0.0)
            self.register_variable(Float64(port, causality=Fmi3Causality.output))
        for index, _ in enumerate(STATES):
            setattr(self, "x%d" % index, 0.0)
            self.register_variable(Float64("x%d" % index, causality=Fmi3Causality.local))
        self.time = 0.0
        self.register_variable(Float64("time", causality=Fmi3Causality.independent,
                                       variability=Fmi3Variability.continuous))
        self.plant_time = 0.0
        self.register_variable(Float64("plant_time", causality=Fmi3Causality.local))
        self._plant = None
        self._initialised = False

    def _make_plant(self):
        values = dict(FIXED)
        values.update({{plant: getattr(self, fmu) for fmu, (plant, _) in PARAMETERS.items()}})
        return _Plant(**values)

    def exit_initialization_mode(self):
        self._plant = self._make_plant()
        for index, value in enumerate(self._plant.initial_state()):
            setattr(self, "x%d" % index, float(value))
        self._initialised = True
        self._update_outputs(self.plant_time)

    def _inputs(self):
        return {{port: getattr(self, port) for port in INPUTS}}

    def _update_outputs(self, t):
        state = [getattr(self, "x%d" % i) for i in range(len(STATES))]
        values = self._plant.output(t, state, self._inputs())
        for port in OUTPUTS:
            setattr(self, port, float(values[port]))

    def do_step(self, current_time, step_size):
        if self._plant is None:          # restored into a fresh instance
            self._plant = self._make_plant()
        u = self._inputs()
        x = [getattr(self, "x%d" % i) for i in range(len(STATES))]
        steps = max(1, math.ceil(step_size / MAX_STEP - 1e-9)) if step_size > 0 else 0
        h = step_size / steps if steps else 0.0
        t, f = current_time, self._plant.derivatives
        for _ in range(steps):
            k1 = f(t, x, u)
            k2 = f(t + h / 2, [a + h / 2 * b for a, b in zip(x, k1)], u)
            k3 = f(t + h / 2, [a + h / 2 * b for a, b in zip(x, k2)], u)
            k4 = f(t + h, [a + h * b for a, b in zip(x, k3)], u)
            x = [a + h / 6 * (b1 + 2 * b2 + 2 * b3 + b4) for a, b1, b2, b3, b4 in zip(x, k1, k2, k3, k4)]
            t += h
        for index, value in enumerate(x):
            setattr(self, "x%d" % index, value)
        self.plant_time = current_time + step_size
        self.time = self.plant_time
        self._update_outputs(self.plant_time)
        return True
'''


def _fmu_name(name: str, taken: set[str]) -> str:
    candidate = name if name.isidentifier() and not keyword.iskeyword(name) else f"p_{name}"
    while candidate in taken:
        candidate = f"p_{candidate}"
    taken.add(candidate)
    return candidate


def describe_plant(reference: str, root: Path | None = None, parameters: Mapping[str, Any] | None = None,
                   input_start: Mapping[str, float] | None = None) -> dict[str, Any]:
    """Interface of a plant class as the FMU will expose it."""
    cls = load_plant_class(reference, root)
    for attribute in ("inputs", "outputs", "states", "initial_state", "derivatives", "output"):
        if not hasattr(cls, attribute):
            raise ValueError(f"{reference} is not a plant class (missing {attribute})")
    overrides = dict(parameters or {})
    signature = inspect.signature(cls.__init__)
    unknown = set(overrides) - set(signature.parameters)
    if unknown:
        raise ValueError(f"{reference} has no parameters {sorted(unknown)}")
    taken = set(cls.inputs) | set(cls.outputs) | {"plant_time", "time"} | {f"x{i}" for i in range(len(cls.states))}
    tunable: dict[str, tuple[str, float]] = {}
    fixed: dict[str, Any] = {}
    for name, param in signature.parameters.items():
        if name == "self" or param.kind in (param.VAR_POSITIONAL, param.VAR_KEYWORD):
            continue
        value = overrides.get(name, param.default)
        if value is inspect.Parameter.empty:
            raise ValueError(f"{reference}: parameter {name} has no default; pass it in `parameters`")
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            tunable[_fmu_name(name, taken)] = (name, float(value))
        elif isinstance(value, (str, bool)) or value is None:
            fixed[name] = value
        else:
            fixed[name] = list(value)
    starts = {name: float(value) for name, value in dict(input_start or {}).items()}
    unknown_inputs = set(starts) - set(cls.inputs)
    if unknown_inputs:
        raise ValueError(f"{reference} has no inputs {sorted(unknown_inputs)}")
    by_plant_name = {plant: value for plant, value in tunable.values()}
    for port in cls.inputs:
        starts.setdefault(port, by_plant_name.get(port, 0.0))
    return {"class": cls, "parameters": tunable, "fixed": fixed, "inputs": list(cls.inputs), "input_start": starts,
            "outputs": list(cls.outputs), "states": list(cls.states)}


def export_plant(reference: str, destination: Path | str = ".", *, name: str | None = None,
                 parameters: Mapping[str, Any] | None = None, input_start: Mapping[str, float] | None = None,
                 max_step: float = 1e-4, root: Path | None = None) -> Path:
    """Build `<name>.fmu` (FMI 3.0 co-simulation, state save/restore) for a plant."""
    try:
        from pythonfmu3 import FmuBuilder
    except ImportError as error:
        raise RuntimeError("FMU export needs pythonfmu3 (pip install 'embeddyn[fmi]')") from error
    if not max_step > 0:
        raise ValueError("max_step must be positive")
    info = describe_plant(reference, root, parameters, input_start)
    cls = info["class"]
    name = name or cls.__name__
    if not name.isidentifier():
        raise ValueError(f"FMU name {name!r} must be a Python identifier")
    module = importlib.import_module(cls.__module__) if cls.__module__ in importlib.sys.modules else None
    source = Path(inspect.getsourcefile(module or cls))
    module_name = f"plant_{source.stem}"
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    doc = (cls.__doc__ or name).strip().splitlines()[0]
    with tempfile.TemporaryDirectory(prefix="embeddyn-fmu-export-") as tmp:
        work = Path(tmp)
        shutil.copy2(source, work / f"{module_name}.py")
        script = work / f"{name}.py"
        script.write_text(_TEMPLATE.format(
            reference=reference, module=module_name, cls=cls.__name__, name=name, description=doc,
            parameters=info["parameters"], fixed=info["fixed"], inputs=info["inputs"], input_start=info["input_start"],
            outputs=info["outputs"], states=info["states"], max_step=float(max_step)), encoding="utf-8")
        built = FmuBuilder.build_FMU(script, dest=destination, project_files=[work / f"{module_name}.py"],
                                     canGetAndSetFMUState=True, canSerializeFMUState=True)
    return Path(built)


def check_fmu(path: Path | str, stop_time: float = 0.01, step: float | None = None) -> dict[str, Any]:
    """FMPy validation plus a short simulation. Returns {valid, problems, fmi_version, variables, simulated}."""
    try:
        from fmpy import read_model_description, simulate_fmu
        from fmpy.validation import validate_fmu
    except ImportError as error:
        raise RuntimeError("FMU checks need fmpy (pip install 'embeddyn[fmi]')") from error
    path = Path(path)
    problems = list(validate_fmu(str(path)))
    result: dict[str, Any] = {"fmu": path.name, "problems": problems, "simulated": False}
    try:
        description = read_model_description(str(path))
    except Exception as error:      # noqa: BLE001 - reported, not raised
        result.update(valid=False, problems=problems + [f"modelDescription: {error}"])
        return result
    result["fmi_version"] = description.fmiVersion
    result["variables"] = {v.name: v.causality for v in description.modelVariables}
    cosim = description.coSimulation
    result["can_get_set_state"] = bool(getattr(cosim, "canGetAndSetFMUstate", False)) if cosim else False
    result["can_serialize_state"] = bool(getattr(cosim, "canSerializeFMUstate", False)) if cosim else False
    if not problems:
        try:
            rows = simulate_fmu(str(path), stop_time=stop_time, output_interval=step or stop_time / 10,
                                fmi_type="CoSimulation")
            result["simulated"] = len(rows) > 1
        except Exception as error:  # noqa: BLE001
            problems.append(f"simulation: {error}")
    result["valid"] = not problems and result["simulated"]
    return result
